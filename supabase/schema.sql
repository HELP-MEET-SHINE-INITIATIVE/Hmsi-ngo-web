-- HMSI Supabase schema
-- Run this once in the Supabase SQL editor before enabling submissions.

create extension if not exists pgcrypto;

create table if not exists public.fundraisers (
  id text primary key,
  title varchar(160) not null,
  description text not null,
  category text not null check (category in ('medical', 'education', 'housing', 'emergency')),
  target_amount numeric(14, 2) not null check (target_amount > 0),
  raised_amount numeric(14, 2) not null default 0 check (raised_amount >= 0),
  image_url text not null,
  image_path text,
  status text not null default 'active' check (status in ('active', 'pending', 'archived')),
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create index if not exists fundraisers_status_created_at_idx
  on public.fundraisers (status, created_at desc);

create table if not exists public.contact_messages (
  id uuid primary key default gen_random_uuid(),
  name varchar(160) not null,
  email varchar(320) not null,
  message text not null,
  status text not null default 'new' check (status in ('new', 'read', 'resolved')),
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.signup_requests (
  id bigint generated by default as identity primary key,
  name varchar(160) not null,
  email varchar(320) not null,
  phone varchar(64),
  message text,
  created_at timestamptz not null default timezone('utc', now())
);

alter table public.fundraisers enable row level security;
alter table public.contact_messages enable row level security;
alter table public.signup_requests enable row level security;

drop policy if exists "Anyone can view active fundraisers" on public.fundraisers;
create policy "Anyone can view active fundraisers"
  on public.fundraisers for select
  using (status = 'active');

-- Inserts and updates are intentionally service-role-only through the server API.

drop policy if exists "Public can read fundraiser images" on storage.objects;
